#!/usr/bin/env node
// ============================================================
// SHADDAI Agents MCP — expose your 7 SHADDAI agents (real tools + agentic loop)
// to Claude Code / Cursor / any MCP client. Zero-dependency; proxies to your
// running SHADDAI backend (default http://localhost:3000, override SHADDAI_URL).
// ============================================================
const http = require('http'); const https = require('https');
const fs = require('fs'); const path = require('path'); const os = require('os');
const BASE = (process.env.SHADDAI_URL || 'http://localhost:3000').replace(/\/$/, '');
let PKG = { version: '0.0.0' }; try { PKG = require('./package.json'); } catch (_) {}
// stdout must be pure JSON-RPC — send any stray log to stderr
console.log = console.info = console.debug = function () { try { process.stderr.write(Array.prototype.join.call(arguments, ' ') + '\n'); } catch (_) {} };

const AGENTS = [
  ['SHADDAI', 'Supreme Orchestrator — strategy, multi-agent coordination, executive summaries'],
  ['NEXUS', 'Technical Architect — runs code (JS/Python), GitHub, npm, security scans, code analysis'],
  ['ZEROX', 'Wealth & Revenue — live prices, OHLCV, DeFi TVL, whale scan, trade math'],
  ['ORACLE', 'Research & Intelligence — web / wikipedia / arxiv / reddit / hackernews research + synthesis'],
  ['TURTLE', 'UI/UX & Creative — image generation, color palettes, diagrams, design'],
  ['QUILL', 'Writing & Communication — copy, docs, translation, publishing (discord/telegram)'],
  ['PIKADON', 'Security & Compliance — code audits, security checks, JSON/complexity validation'],
];
const NAMES = AGENTS.map(a => a[0]);
const MAX = 12000;
const clip = (s) => { s = String(s == null ? '' : s); return s.length > MAX ? s.slice(0, MAX) : s; };

// ------------------------------------------------------------
// NVIDIA skills — NVIDIA/skills installed at ~/.agents/skills
// Manifest is generated by build-nvidia-skills-manifest.js and
// lists all curated skills with real frontmatter descriptions.
// SKILL.md bodies are read from disk at call time so this repo
// stays small; only ids present in the manifest can be read.
// ------------------------------------------------------------
const SKILL_ROOT = path.join(os.homedir(), '.agents', 'skills');
const NVIDIA_MANIFEST = (() => {
  try {
    const raw = fs.readFileSync(path.join(__dirname, 'nvidia-skills.json'), 'utf8');
    const m = JSON.parse(raw);
    return (m && Array.isArray(m.skills)) ? m : { count: 0, skills: [], gpuNote: 'manifest empty' };
  } catch (e) {
    return { count: 0, skills: [], gpuNote: 'nvidia-skills.json not found next to mcp.js' };
  }
})();
const NVIDIA_BY_ID = new Map(NVIDIA_MANIFEST.skills.map(s => [s.id, s]));

function nvidiaSkillBody(id) {
  const entry = NVIDIA_BY_ID.get(id);
  if (!entry) return null;
  // Resolve strictly from the manifest id (no user-controlled path),
  // then confirm the resolved file is still inside the skill root.
  const resolved = path.resolve(path.join(SKILL_ROOT, entry.id, 'SKILL.md'));
  const root = path.resolve(SKILL_ROOT) + path.sep;
  if (!resolved.startsWith(root)) return null;
  try {
    return { entry: entry, body: fs.readFileSync(resolved, 'utf8') };
  } catch (e) {
    return { entry: entry, body: '(SKILL.md could not be read at ' + resolved + ')' };
  }
}

function nvidiaSearch(query, category) {
  let list = NVIDIA_MANIFEST.skills.slice();
  if (category) list = list.filter(s => String(s.category).toLowerCase() === String(category).toLowerCase());
  if (query) {
    // Token-AND search: every word must appear somewhere in the record.
    const tokens = String(query).toLowerCase().split(/[^a-z0-9_.+-]+/).filter(Boolean);
    list = list.filter(s => {
      const hay = (s.id + ' ' + s.name + ' ' + s.description + ' ' + s.sapRelevance + ' ' + s.category).toLowerCase();
      return tokens.every(t => hay.indexOf(t) >= 0);
    });
  }
  return list;
}

function req(method, path, body) {
  return new Promise((resolve, reject) => {
    let u; try { u = new URL(BASE + path); } catch (e) { return reject(e); }
    const mod = u.protocol === 'https:' ? https : http;
    const data = body ? JSON.stringify(body) : null;
    const r = mod.request(u, { method, headers: Object.assign({ 'Content-Type': 'application/json' }, data ? { 'Content-Length': Buffer.byteLength(data) } : {}) }, (res) => {
      let s = ''; res.on('data', c => s += c); res.on('end', () => { try { resolve(JSON.parse(s)); } catch (e) { resolve({ raw: s }); } });
    });
    r.on('error', reject);
    r.setTimeout(20000, () => r.destroy(new Error('backend not reachable at ' + BASE + ' — is SHADDAI running (START-SHADDAI.bat)?')));
    if (data) r.write(data); r.end();
  });
}
const sleep = (ms) => new Promise(r => setTimeout(r, ms));

async function chat(agent, message) {
  const r = await req('POST', '/api/agents/route', { agentName: agent, message: clip(message) });
  return { agent, response: (r && (r.response || r.message || r.answer)) || '(no response)', model: r && r.model };
}

async function task(agent, goal) {
  const start = await req('POST', '/api/agent/autonomous', { agent, goal: clip(goal) });
  const id = start && (start.taskId || start.id);
  if (!id) return { error: 'could not start task', detail: JSON.stringify(start).slice(0, 200) };
  for (let i = 0; i < 60; i++) { // up to ~90s
    await sleep(1500);
    const t = await req('GET', '/api/agent/task/' + id).catch(() => ({}));
    const task = (t && (t.task || t)) || {};
    const status = task.status;
    const answer = task.answer || task.result || task.output || task.finalAnswer;
    if (status === 'completed' || status === 'done' || status === 'failed' || answer) {
      return { status: status || 'done', agent, answer: answer || '(completed, no text output)', toolsUsed: task.toolsUsed || task.tools, taskId: id };
    }
  }
  return { status: 'running', note: 'still running after ~90s; poll ' + BASE + '/api/agent/task/' + id, taskId: id };
}

const TOOLS = [
  { name: 'shaddai_list_agents', description: 'List the 7 SHADDAI agents and what each specializes in. Call first to pick the right agent.',
    inputSchema: { type: 'object', properties: {} } },
  { name: 'shaddai_ask', description: 'Ask a SHADDAI agent a quick question (fast, single reply — no heavy tool use). Good for quick expertise from a specific agent.',
    inputSchema: { type: 'object', properties: { agent: { type: 'string', enum: NAMES, description: 'Which agent' }, message: { type: 'string' } }, required: ['agent', 'message'] } },
  { name: 'shaddai_task', description: 'Give a SHADDAI agent a real AGENTIC task — it uses its real tools (run code, fetch live data, search, analyze) over multiple steps and returns the finished work. Use for actual jobs, not chit-chat. Takes up to ~90s.',
    inputSchema: { type: 'object', properties: { agent: { type: 'string', enum: NAMES, description: 'Which agent runs the job' }, goal: { type: 'string', description: 'The concrete task to complete' } }, required: ['agent', 'goal'] } },
  { name: 'nvidia_skills', description: 'Explore the installed NVIDIA/skills library (48 curated skills: Omniverse/Cosmos physical AI, Earth2Studio climate, RAG, TAO, FoundationPose). Call with no arguments to list every skill; pass skill=<id> to read that skill\'s full SKILL.md; pass query=<text> or category=<name> to filter.',
    inputSchema: { type: 'object', properties: {
      skill: { type: 'string', description: 'Exact skill id, e.g. earth2studio-deterministic-forecast. Returns the full SKILL.md.' },
      query: { type: 'string', description: 'Keyword filter over id, name, description and SAP relevance.' },
      category: { type: 'string', description: 'Filter by category: omniverse, physical-ai, cosmos, climate, rag, vision, tao, data, meta' }
    } } },
];

function textResult(obj) { return { content: [{ type: 'text', text: typeof obj === 'string' ? obj : JSON.stringify(obj, null, 2) }] }; }
async function callTool(name, a) {
  a = a || {};
  const agent = String(a.agent || '').toUpperCase();
  if (name === 'shaddai_list_agents') return textResult({ agents: AGENTS.map(([n, d]) => ({ name: n, does: d })), backend: BASE });
  if (name === 'shaddai_ask') { if (!NAMES.includes(agent)) return Object.assign(textResult('Unknown agent. Use one of: ' + NAMES.join(', ')), { isError: true }); return textResult(await chat(agent, a.message)); }
  if (name === 'shaddai_task') { if (!NAMES.includes(agent)) return Object.assign(textResult('Unknown agent. Use one of: ' + NAMES.join(', ')), { isError: true }); return textResult(await task(agent, a.goal)); }
  if (name === 'nvidia_skills') {
    const skillId = a.skill ? String(a.skill).trim() : '';
    const query = a.query ? String(a.query).trim() : '';
    const category = a.category ? String(a.category).trim() : '';
    if (skillId) {
      const got = nvidiaSkillBody(skillId);
      if (!got) return Object.assign(textResult('Unknown NVIDIA skill: ' + skillId + '. Call nvidia_skills with no arguments to list all ' + NVIDIA_MANIFEST.count + ' installed skills.'), { isError: true });
      return textResult({
        id: got.entry.id, name: got.entry.name, category: got.entry.category,
        requiresGpu: got.entry.requiresGpu, sapRelevance: got.entry.sapRelevance,
        description: got.entry.description, content: got.body
      });
    }
    const list = nvidiaSearch(query, category);
    if (!list.length) {
      return textResult({ matched: 0, note: 'No NVIDIA skill matched that filter.', available: NVIDIA_MANIFEST.skills.map(s => s.id) });
    }
    const cats = {};
    for (const s of list) cats[s.category] = (cats[s.category] || 0) + 1;
    return textResult({
      total: NVIDIA_MANIFEST.count, matched: list.length, categories: cats,
      gpuNote: NVIDIA_MANIFEST.gpuNote,
      skills: list.map(s => ({
        id: s.id, category: s.category, requiresGpu: s.requiresGpu,
        description: s.description, sapRelevance: s.sapRelevance
      }))
    });
  }
  return Object.assign(textResult('Unknown tool: ' + name), { isError: true });
}

// ── MCP stdio JSON-RPC ──
function send(m) { process.stdout.write(JSON.stringify(m) + '\n'); }
function ok(id, result) { send({ jsonrpc: '2.0', id, result }); }
function fail(id, code, message) { send({ jsonrpc: '2.0', id, error: { code, message } }); }
async function handle(msg) {
  const { id, method, params } = msg || {};
  if (method === 'initialize') return ok(id, { protocolVersion: (params && params.protocolVersion) || '2024-11-05', capabilities: { tools: {} }, serverInfo: { name: 'shaddai-agents', version: PKG.version } });
  if (method === 'notifications/initialized' || method === 'initialized') return;
  if (method === 'ping') return ok(id, {});
  if (method === 'resources/list') return ok(id, { resources: [] });
  if (method === 'prompts/list') return ok(id, { prompts: [] });
  if (method === 'tools/list') return ok(id, { tools: TOOLS });
  if (method === 'tools/call') { try { return ok(id, await callTool(params && params.name, params && params.arguments)); } catch (e) { return ok(id, Object.assign(textResult('Error: ' + ((e && e.message) || e)), { isError: true })); } }
  if (id !== undefined && id !== null) fail(id, -32601, 'Method not found: ' + method);
}
let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => { buf += c; let i; while ((i = buf.indexOf('\n')) >= 0) { const line = buf.slice(0, i).trim(); buf = buf.slice(i + 1); if (!line) continue; let m; try { m = JSON.parse(line); } catch (_) { continue; } handle(m); } });
process.stdin.on('end', () => process.exit(0));
